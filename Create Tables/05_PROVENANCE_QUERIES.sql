SELECT
    AUDIT_ID,
    RECORD_ID AS MENU_ITEM_ID,
    OPERATION_TYPE,
    OLD_PRICE,
    NEW_PRICE,
    CHANGED_BY,
    CHANGED_AT
FROM AUDIT_MENU_ITEMS
WHERE RECORD_ID = '203'
ORDER BY CHANGED_AT;



SELECT
    AUDIT_ID,
    RECORD_ID AS ORDER_ID,
    OPERATION_TYPE,
    OLD_ORDER_STATUS,
    NEW_ORDER_STATUS,
    CHANGED_BY,
    CHANGED_AT
FROM AUDIT_ORDERS
WHERE RECORD_ID = '5004'
ORDER BY CHANGED_AT;



SELECT
    AUDIT_ID,
    RECORD_ID AS PAYMENT_ID,
    OPERATION_TYPE,
    OLD_PAYMENT_STATUS,
    NEW_PAYMENT_STATUS,
    OLD_AMOUNT,
    NEW_AMOUNT,
    CHANGED_BY,
    CHANGED_AT
FROM AUDIT_PAYMENTS
WHERE RECORD_ID = '7004'
ORDER BY CHANGED_AT;




SELECT
    CHANGED_BY,
    SOURCE_TABLE,
    OPERATION_TYPE,
    COUNT(*) AS NUMBER_OF_CHANGES
FROM (
    SELECT CHANGED_BY, SOURCE_TABLE, OPERATION_TYPE
    FROM AUDIT_CUSTOMERS

    UNION ALL

    SELECT CHANGED_BY, SOURCE_TABLE, OPERATION_TYPE
    FROM AUDIT_MENU_ITEMS

    UNION ALL

    SELECT CHANGED_BY, SOURCE_TABLE, OPERATION_TYPE
    FROM AUDIT_ORDERS

    UNION ALL

    SELECT CHANGED_BY, SOURCE_TABLE, OPERATION_TYPE
    FROM AUDIT_ORDER_ITEMS

    UNION ALL

    SELECT CHANGED_BY, SOURCE_TABLE, OPERATION_TYPE
    FROM AUDIT_PAYMENTS
)
GROUP BY CHANGED_BY, SOURCE_TABLE, OPERATION_TYPE
ORDER BY CHANGED_BY, SOURCE_TABLE, OPERATION_TYPE;



SELECT
    SOURCE_TABLE,
    RECORD_ID,
    OPERATION_TYPE,
    CHANGED_BY,
    CHANGED_AT
FROM (
    SELECT SOURCE_TABLE, RECORD_ID, OPERATION_TYPE, CHANGED_BY, CHANGED_AT
    FROM AUDIT_CUSTOMERS

    UNION ALL

    SELECT SOURCE_TABLE, RECORD_ID, OPERATION_TYPE, CHANGED_BY, CHANGED_AT
    FROM AUDIT_MENU_ITEMS

    UNION ALL

    SELECT SOURCE_TABLE, RECORD_ID, OPERATION_TYPE, CHANGED_BY, CHANGED_AT
    FROM AUDIT_ORDERS

    UNION ALL

    SELECT SOURCE_TABLE, RECORD_ID, OPERATION_TYPE, CHANGED_BY, CHANGED_AT
    FROM AUDIT_ORDER_ITEMS

    UNION ALL

    SELECT SOURCE_TABLE, RECORD_ID, OPERATION_TYPE, CHANGED_BY, CHANGED_AT
    FROM AUDIT_PAYMENTS
)
WHERE CHANGED_AT >= SYSTIMESTAMP - INTERVAL '7' DAY
ORDER BY CHANGED_AT DESC;




SELECT
    AUDIT_ID,
    RECORD_ID AS CUSTOMER_ID,
    OPERATION_TYPE,
    OLD_CUSTOMER_NAME,
    OLD_PHONE,
    OLD_EMAIL,
    OLD_ADDRESS,
    CHANGED_BY,
    CHANGED_AT
FROM AUDIT_CUSTOMERS
WHERE OPERATION_TYPE = 'DELETE'
ORDER BY CHANGED_AT;




SELECT
    M.MENU_ITEM_ID,
    M.ITEM_NAME,
    C.CATEGORY_NAME,
    M.PRICE,
    M.IS_AVAILABLE,
    M.CREATED_AT
FROM MENU_ITEMS M
JOIN CATEGORIES C
    ON M.CATEGORY_ID = C.CATEGORY_ID
WHERE M.MENU_ITEM_ID = 203;



SELECT
    O.ORDER_ID,
    O.ORDER_DATE,
    C.CUSTOMER_NAME,
    E.EMPLOYEE_NAME,
    M.MENU_ITEM_ID,
    M.ITEM_NAME,
    OI.QUANTITY,
    OI.UNIT_PRICE,
    O.TOTAL_AMOUNT,
    O.ORDER_STATUS
FROM ORDERS O
JOIN CUSTOMERS C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID
LEFT JOIN EMPLOYEES E
    ON O.EMPLOYEE_ID = E.EMPLOYEE_ID
JOIN ORDER_ITEMS OI
    ON O.ORDER_ID = OI.ORDER_ID
JOIN MENU_ITEMS M
    ON OI.MENU_ITEM_ID = M.MENU_ITEM_ID
WHERE O.ORDER_ID = 5004
ORDER BY M.MENU_ITEM_ID;



