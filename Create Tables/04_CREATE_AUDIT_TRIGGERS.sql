CREATE OR REPLACE TRIGGER TRG_AUD_CUSTOMERS
AFTER INSERT OR UPDATE OR DELETE ON CUSTOMERS
FOR EACH ROW
DECLARE
    V_USER VARCHAR2(128);
BEGIN
    V_USER := NVL(
        NULLIF(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), ''),
        SYS_CONTEXT('USERENV', 'SESSION_USER')
    );

    IF INSERTING THEN

        INSERT INTO AUDIT_CUSTOMERS (
            SOURCE_TABLE, RECORD_ID, OPERATION_TYPE,
            NEW_CUSTOMER_NAME, NEW_PHONE, NEW_EMAIL,
            NEW_ADDRESS, CHANGED_BY
        )
        VALUES (
            'CUSTOMERS', TO_CHAR(:NEW.CUSTOMER_ID), 'INSERT',
            :NEW.CUSTOMER_NAME, :NEW.PHONE, :NEW.EMAIL,
            :NEW.ADDRESS, V_USER
        );

    ELSIF UPDATING THEN

        INSERT INTO AUDIT_CUSTOMERS (
            SOURCE_TABLE, RECORD_ID, OPERATION_TYPE,
            OLD_CUSTOMER_NAME, NEW_CUSTOMER_NAME,
            OLD_PHONE, NEW_PHONE,
            OLD_EMAIL, NEW_EMAIL,
            OLD_ADDRESS, NEW_ADDRESS,
            CHANGED_BY
        )
        VALUES (
            'CUSTOMERS', TO_CHAR(:NEW.CUSTOMER_ID), 'UPDATE',
            :OLD.CUSTOMER_NAME, :NEW.CUSTOMER_NAME,
            :OLD.PHONE, :NEW.PHONE,
            :OLD.EMAIL, :NEW.EMAIL,
            :OLD.ADDRESS, :NEW.ADDRESS,
            V_USER
        );

    ELSIF DELETING THEN

        INSERT INTO AUDIT_CUSTOMERS (
            SOURCE_TABLE, RECORD_ID, OPERATION_TYPE,
            OLD_CUSTOMER_NAME, OLD_PHONE,
            OLD_EMAIL, OLD_ADDRESS, CHANGED_BY
        )
        VALUES (
            'CUSTOMERS', TO_CHAR(:OLD.CUSTOMER_ID), 'DELETE',
            :OLD.CUSTOMER_NAME, :OLD.PHONE,
            :OLD.EMAIL, :OLD.ADDRESS, V_USER
        );

    END IF;
END;
/



