AFTER INSERT OR UPDATE OR DELETE ON ORDER_ITEMS
FOR EACH ROW
DECLARE
    V_USER VARCHAR2(128);
    V_RECORD_ID VARCHAR2(100);
BEGIN
    V_USER := NVL(
        NULLIF(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), ''),
        SYS_CONTEXT('USERENV', 'SESSION_USER')
    );

    IF INSERTING THEN

        V_RECORD_ID := TO_CHAR(:NEW.ORDER_ID) || '-' ||
                       TO_CHAR(:NEW.MENU_ITEM_ID);

        INSERT INTO AUDIT_ORDER_ITEMS (
            SOURCE_TABLE, RECORD_ID, OPERATION_TYPE,
            NEW_ORDER_ID, NEW_MENU_ITEM_ID,
            NEW_QUANTITY, NEW_UNIT_PRICE,
            CHANGED_BY
        )
        VALUES (
            'ORDER_ITEMS', V_RECORD_ID, 'INSERT',
