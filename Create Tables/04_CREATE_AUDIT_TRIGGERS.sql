        V_RECORD_ID := TO_CHAR(:NEW.ORDER_ID) || '-' ||
                       TO_CHAR(:NEW.MENU_ITEM_ID);

        INSERT INTO AUDIT_ORDER_ITEMS (
            SOURCE_TABLE, RECORD_ID, OPERATION_TYPE,
            OLD_ORDER_ID, NEW_ORDER_ID,
            OLD_MENU_ITEM_ID, NEW_MENU_ITEM_ID,
            OLD_QUANTITY, NEW_QUANTITY,
