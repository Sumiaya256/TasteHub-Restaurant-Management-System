CREATE TABLE AUDIT_CUSTOMERS (
    AUDIT_ID NUMBER GENERATED ALWAYS AS IDENTITY
        PRIMARY KEY,

    SOURCE_TABLE VARCHAR2(30) NOT NULL,
    RECORD_ID VARCHAR2(100) NOT NULL,
    OPERATION_TYPE VARCHAR2(10) NOT NULL,

    OLD_CUSTOMER_NAME VARCHAR2(100),
    NEW_CUSTOMER_NAME VARCHAR2(100),

    OLD_PHONE VARCHAR2(15),
    NEW_PHONE VARCHAR2(15),

    OLD_EMAIL VARCHAR2(120),
    NEW_EMAIL VARCHAR2(120),

    OLD_ADDRESS VARCHAR2(250),
    NEW_ADDRESS VARCHAR2(250),

    CHANGED_BY VARCHAR2(128) NOT NULL,
    CHANGED_AT TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT CHK_AUD_CUST_OP
        CHECK (OPERATION_TYPE IN
        ('INSERT', 'UPDATE', 'DELETE'))
);



