DROP TABLE PAYMENTS CASCADE CONSTRAINTS;
DROP TABLE ORDER_ITEMS CASCADE CONSTRAINTS;
DROP TABLE ORDERS CASCADE CONSTRAINTS;
DROP TABLE MENU_ITEMS CASCADE CONSTRAINTS;
DROP TABLE EMPLOYEES CASCADE CONSTRAINTS;
DROP TABLE CUSTOMERS CASCADE CONSTRAINTS;
DROP TABLE CATEGORIES CASCADE CONSTRAINTS;
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID NUMBER(6) PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(15) NOT NULL UNIQUE,
    EMAIL VARCHAR2(120) UNIQUE,
    ADDRESS VARCHAR2(250),
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL
);


CREATE TABLE CATEGORIES (
    CATEGORY_ID NUMBER(4) PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(60) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(200)
);


CREATE TABLE MENU_ITEMS (
    MENU_ITEM_ID NUMBER(6) PRIMARY KEY,
    ITEM_NAME VARCHAR2(120) NOT NULL,
    CATEGORY_ID NUMBER(4) NOT NULL,
    DESCRIPTION VARCHAR2(250),
    PRICE NUMBER(10,2) NOT NULL,
    IS_AVAILABLE CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT FK_MENU_CATEGORY
        FOREIGN KEY (CATEGORY_ID)
        REFERENCES CATEGORIES(CATEGORY_ID),

    CONSTRAINT CHK_MENU_PRICE
        CHECK (PRICE >= 0),

    CONSTRAINT CHK_MENU_AVAILABLE
        CHECK (IS_AVAILABLE IN ('Y', 'N'))
);

CREATE TABLE EMPLOYEES (
    EMPLOYEE_ID NUMBER(6) PRIMARY KEY,
    EMPLOYEE_NAME VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(15) NOT NULL UNIQUE,
    EMAIL VARCHAR2(120) UNIQUE,
    JOB_ROLE VARCHAR2(30) NOT NULL,
    HIRE_DATE DATE DEFAULT SYSDATE NOT NULL,
    SALARY NUMBER(10,2),
    EMPLOYEE_STATUS VARCHAR2(15) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT CHK_EMP_ROLE
        CHECK (JOB_ROLE IN
        ('MANAGER', 'CASHIER', 'WAITER', 'CHEF')),

    CONSTRAINT CHK_EMP_SALARY
        CHECK (SALARY IS NULL OR SALARY >= 0),

    CONSTRAINT CHK_EMP_STATUS
        CHECK (EMPLOYEE_STATUS IN ('ACTIVE', 'INACTIVE'))
);


CREATE TABLE ORDERS (
    ORDER_ID NUMBER(8) PRIMARY KEY,
    CUSTOMER_ID NUMBER(6) NOT NULL,
    EMPLOYEE_ID NUMBER(6),
    ORDER_DATE DATE DEFAULT SYSDATE NOT NULL,
    ORDER_TYPE VARCHAR2(20) DEFAULT 'DINE_IN' NOT NULL,
    ORDER_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    TOTAL_AMOUNT NUMBER(10,2) DEFAULT 0 NOT NULL,

    CONSTRAINT FK_ORDER_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMERS(CUSTOMER_ID),

    CONSTRAINT FK_ORDER_EMPLOYEE
        FOREIGN KEY (EMPLOYEE_ID)
        REFERENCES EMPLOYEES(EMPLOYEE_ID),

    CONSTRAINT CHK_ORDER_TYPE
        CHECK (ORDER_TYPE IN
        ('DINE_IN', 'TAKEAWAY', 'DELIVERY')),

    CONSTRAINT CHK_ORDER_STATUS
        CHECK (ORDER_STATUS IN
        ('PENDING', 'CONFIRMED', 'PREPARING',
         'READY', 'COMPLETED', 'CANCELLED')),

    CONSTRAINT CHK_ORDER_TOTAL
        CHECK (TOTAL_AMOUNT >= 0)
);


CREATE TABLE ORDER_ITEMS (
    ORDER_ID NUMBER(8) NOT NULL,
    MENU_ITEM_ID NUMBER(6) NOT NULL,
    QUANTITY NUMBER(5) NOT NULL,
    UNIT_PRICE NUMBER(10,2) NOT NULL,

    CONSTRAINT PK_ORDER_ITEMS
        PRIMARY KEY (ORDER_ID, MENU_ITEM_ID),

    CONSTRAINT FK_ITEM_ORDER
        FOREIGN KEY (ORDER_ID)
        REFERENCES ORDERS(ORDER_ID),

    CONSTRAINT FK_ITEM_MENU
        FOREIGN KEY (MENU_ITEM_ID)
        REFERENCES MENU_ITEMS(MENU_ITEM_ID),

    CONSTRAINT CHK_ITEM_QUANTITY
        CHECK (QUANTITY > 0),

    CONSTRAINT CHK_ITEM_PRICE
        CHECK (UNIT_PRICE >= 0)
);


CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER(8) PRIMARY KEY,
    ORDER_ID NUMBER(8) NOT NULL,
    PAYMENT_DATE DATE DEFAULT SYSDATE NOT NULL,
    AMOUNT NUMBER(10,2) NOT NULL,
    PAYMENT_METHOD VARCHAR2(20) NOT NULL,
    PAYMENT_STATUS VARCHAR2(15) DEFAULT 'PENDING' NOT NULL,

    CONSTRAINT FK_PAYMENT_ORDER
        FOREIGN KEY (ORDER_ID)
        REFERENCES ORDERS(ORDER_ID),

    CONSTRAINT CHK_PAYMENT_AMOUNT
        CHECK (AMOUNT > 0),

    CONSTRAINT CHK_PAYMENT_METHOD
        CHECK (PAYMENT_METHOD IN
        ('CASH', 'CARD', 'BKASH', 'NAGAD')),

    CONSTRAINT CHK_PAYMENT_STATUS
        CHECK (PAYMENT_STATUS IN
        ('PENDING', 'PAID', 'FAILED', 'REFUNDED'))
);
